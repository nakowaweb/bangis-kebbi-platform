export const dictionaries: Record<LanguageCode, Record<TranslationKey, string>> = { en, ha, ar };

export function translate(language: LanguageCode, key: TranslationKey): string {
  return dictionaries[language][key] || dictionaries.en[key];
}

/** Formats a UTC timestamp for display in the selected language. Storage stays UTC. */
export function formatDate(value: string | Date | null | undefined, language: LanguageCode, withTime = false): string {
  if (!value) return "";
  const date = typeof value === "string" ? new Date(value) : value;
  if (Number.isNaN(date.getTime())) return "";
  const { locale } = languageMeta(language);
  return new Intl.DateTimeFormat(locale, {
    year: "numeric",
    month: "long",
    day: "numeric",
    ...(withTime ? { hour: "2-digit", minute: "2-digit" } : {}),
  }).format(date);
}
